#!/usr/bin/env python3
"""Regenerate docs/_links.md, the site-wide reference-link library.

Adapted from the Agda Universal Algebra Library's ``scripts/python/gen_links.py``
(Apache-2.0; see NOTICE).

`pymdownx.snippets` appends docs/_links.md to every page, so any module can
write reference-style links, `[Lattices.Free.Term][]`, `[Setoid.Algebras.Basic][]`,
`[Freese, Ježek, and Nation (1995)][]`, and have them resolve.  This tool
regenerates the GENERATED sections from the trees:

  + one `[Dotted.Module]: /Slashed/Module.md` per module under src/; the
    target is relative to the docs directory (mkdocs.yml:
    `absolute_links: relative_to_docs`), so MkDocs checks that the page
    exists and writes the link relative to the page it is on;
  + one `[Dotted.Module]: <sibling>/Slashed/Module/` per module of the
    pinned Agda Universal Algebra Library that the prose names, pointing at
    its page on that library's site (mkdocs.yml: `extra.agda_algebras`);
  + the external links (citations and the like) carried over verbatim from
    the existing file, where new ones are added by hand.

Run from the repository root inside `nix develop` (idempotent):

    python3 scripts/python/gen_links.py

Pass --check to verify that the committed file is exactly what this tool
produces, and exit non-zero with a diff if it has drifted; `make check-links`
runs it so a new module or a new citation of agda-algebras cannot ship a
broken reference-style link.
"""
from __future__ import annotations

import argparse
import difflib
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_links import iter_uses, pages  # noqa: E402

SRC = Path("src")
LINKS = Path("docs/_links.md")
MKDOCS = Path("mkdocs.yml")

HEADER = """\
<!-- File: docs/_links.md -->
<!-- The site's reference-link library.  pymdownx.snippets appends this file -->
<!-- to every page, so reference-style links resolve site-wide.  The module -->
<!-- sections are GENERATED by scripts/python/gen_links.py from src/ and the -->
<!-- pinned agda-algebras; re-run it (make gen-links) rather than editing them -->
<!-- by hand (make check-links runs it with --check).  New external links may -->
<!-- be added by hand to the External-links section. -->
"""


def sibling_url(mkdocs_yml: str) -> str:
    """The sibling site's URL, from mkdocs.yml's `extra.agda_algebras`."""
    m = re.search(r"^\s+agda_algebras:\s*(\S+)\s*$", mkdocs_yml, re.MULTILINE)
    if not m:
        raise SystemExit(f"{MKDOCS}: no extra.agda_algebras")
    url = m.group(1)
    return url if url.endswith("/") else url + "/"


def module_names(root: Path) -> list[str]:
    return sorted(".".join(p.relative_to(root).as_posix()[: -len(".lagda.md")].split("/"))
                  for p in root.rglob("*.lagda.md"))


def used_labels() -> set[str]:
    """Every reference label the rendered corpus uses, as written."""
    out: set[str] = set()
    for page in pages():
        for _, _, raw in iter_uses(page.read_text(encoding="utf-8")):
            m = re.match(r"\[([^\]]+)\]\[([^\]]*)\]", raw)
            if m:
                out.add((m.group(2) or m.group(1)).strip())
    return out


def is_generated(label: str, target: str, sibling: str) -> bool:
    """A definition in a shape a generated section emits.  Carry-over drops
    these: a module that still exists is re-emitted, and one that is gone
    must not survive among the external links."""
    slashed = label.replace(".", "/")
    return target in (f"/{slashed}.md", f"{sibling}{slashed}/")


def carried_over_links(skip: set[str], sibling: str) -> list[str]:
    out, seen = [], set()
    existing = LINKS.read_text(encoding="utf-8").splitlines() if LINKS.exists() else []
    in_external = False
    for line in existing:
        if line.startswith("<!-- ===== External links"):
            in_external = True
            continue
        if not in_external:
            continue
        m = re.match(r"^\[([^\]]+)\]:\s*(\S+)", line)
        if not m:
            continue
        label, target = m.group(1), m.group(2)
        key = label.lower()
        if key in skip or key in seen or is_generated(label, target, sibling):
            continue
        seen.add(key)
        out.append(line)
    return out


def render(algebras_src: Path) -> str:
    sibling = sibling_url(MKDOCS.read_text(encoding="utf-8"))
    ours = module_names(SRC)
    theirs = set(module_names(algebras_src))
    named = sorted(label for label in used_labels() if label in theirs)

    skip = {m.lower() for m in ours} | {m.lower() for m in named}
    return (
        HEADER
        + "\n<!-- ===== This library's module pages ===== -->\n"
        + "\n".join(f"[{m}]: /{m.replace('.', '/')}.md" for m in ours)
        + "\n\n<!-- ===== The Agda Universal Algebra Library's module pages ===== -->\n"
        + "\n".join(f"[{m}]: {sibling}{m.replace('.', '/')}/" for m in named)
        + "\n\n<!-- ===== External links ===== -->\n"
        + "\n".join(carried_over_links(skip, sibling))
        + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail (with a diff) if docs/_links.md is out of sync")
    ap.add_argument("--algebras", type=Path,
                    default=Path(os.environ.get("ALGEBRAS", ".deps/agda-algebras")),
                    help="the pinned agda-algebras checkout (default: $ALGEBRAS, "
                         "which the dev shell sets, else .deps/agda-algebras)")
    args = ap.parse_args()

    algebras_src = args.algebras / "src"
    if not algebras_src.is_dir():
        sys.stderr.write(f"error: {algebras_src} not found; run inside `nix develop`\n")
        return 2

    body = render(algebras_src)
    if args.check:
        current = LINKS.read_text(encoding="utf-8") if LINKS.exists() else ""
        if current != body:
            diff = difflib.unified_diff(
                current.splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"{LINKS} (committed)", tofile=f"{LINKS} (regenerated)")
            sys.stderr.write("".join(diff))
            sys.stderr.write(f"\n{LINKS} is out of sync with the trees.\n"
                             "Run:  make gen-links\n")
            return 1
        print(f"{LINKS} is up to date.")
        return 0

    LINKS.write_text(body, encoding="utf-8")
    print(f"wrote {LINKS}: {len(body.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
